#!/usr/bin/env python3
"""Analysis-only independent encryption of our original PDF fixture.

The literal password is public fixture data, never a real credential.
PyMuPDF is not an SDK or CLI runtime dependency. AES random salts/IVs mean the
generated bytes have their own recorded digest rather than a reproducible seed.
"""
from pathlib import Path
import pymupdf

root = Path(__file__).resolve().parents[1]
with pymupdf.open(root / "tests/Fluent.Pdf.Contract.Tests/Fixtures/Automation/original.pdf") as pdf:
    pdf.save(root / "tests/Fluent.Pdf.Contract.Tests/Fixtures/Cli/encrypted.pdf",
             encryption=pymupdf.PDF_ENCRYPT_AES_256, owner_pw="cli-fixture-owner",
             user_pw="cli-fixture-password", permissions=pymupdf.PDF_PERM_PRINT)
print("Generated original independently encrypted CLI fixture; PyMuPDF", pymupdf.VersionBind)
