using System.IO;
using System.Threading;

namespace Fluent.Pdf;
/// <summary>An isolated editable overlay over an immutable object graph; mutation and saving must be serialized by the caller.</summary>
public sealed class PdfTransaction : IDisposable
{
    private readonly Dictionary<PdfObjectId, PdfValue> _changes = new();
    private readonly HashSet<PdfObjectId> _removed = new();
    private readonly PdfOperationPolicy _policy;
    private PdfValue _trailer;
    private int _maximum;
    private bool _disposed, _writing, _trailerChanged;
    /// <summary>Creates a new graph or an editing overlay. The source remains immutable and owns no caller stream.</summary>
    public PdfTransaction(PdfSyntaxDocument? source = null, PdfOperationPolicy? policy = null)
    {
        Source = source;
        _policy = policy ?? source?.ReadPolicy ?? PdfOperationPolicy.Default;
        _trailer = PdfWriterCore.TrailerFrom(source);
        if (source != null)
            foreach (var revision in source.Revisions)
            {
                foreach (var entry in revision.Entries)
                    _maximum = Math.Max(_maximum, entry.Id.Number);
                if (revision.Trailer.Entries.TryGetValue("Size", out var size))
                    _maximum = Math.Max(_maximum, checked((int)(size.IntegerValue - 1)));
            }
    }

    /// <summary>Gets the immutable original graph, or null for a new file.</summary>
    public PdfSyntaxDocument? Source { get; }

    /// <summary>Gets or sets a direct trailer dictionary. Structural xref keys are generated by the writer.</summary>
    public PdfValue Trailer
    {
        get
        {
            Alive();
            return _trailer;
        }

        set
        {
            Editable();
            if (value == null)
                throw new ArgumentNullException(nameof(value));
            if (value.Kind != PdfValueKind.Dictionary)
                throw new ArgumentException("A direct trailer dictionary is required.", nameof(value));
            _trailer = value;
            _trailerChanged = true;
        }
    }

    /// <summary>Gets the last save report, including a failed save. Remains readable after disposal.</summary>
    public PdfOperationReport? LastOperationReport { get; private set; }

    /// <summary>Adds an immutable value with a fresh generation-zero identity, without reusing old identities.</summary>
    public PdfObjectId Add(PdfValue value)
    {
        Editable();
        if (value == null)
            throw new ArgumentNullException(nameof(value));
        CheckGrowth(true);
        if (_maximum >= int.MaxValue - 2)
            throw Failure("Writer.ObjectNumberLimit", "The object identity space is exhausted.");
        var id = new PdfObjectId(++_maximum);
        _changes.Add(id, value);
        return id;
    }

    /// <summary>Resolves the exact active generation through this overlay. Missing/free identities resolve to PDF null.</summary>
    public PdfValue Resolve(PdfObjectId id)
    {
        Alive();
        return _removed.Contains(id) ? PdfValue.Null : _changes.TryGetValue(id, out var value) ? value : Source?.Resolve(id) ?? PdfValue.Null;
    }

    /// <summary>Replaces an existing active identity, preserving its number and generation.</summary>
    public void Set(PdfObjectId id, PdfValue value)
    {
        Editable();
        if (value == null)
            throw new ArgumentNullException(nameof(value));
        if (!Exists(id))
            throw new ArgumentException("The exact active object generation is required.", nameof(id));
        CheckGrowth(!_changes.ContainsKey(id));
        _changes[id] = value;
    }

    /// <summary>Frees an active identity. References to that generation resolve to null.</summary>
    public void Remove(PdfObjectId id)
    {
        Editable();
        if (!Exists(id))
            throw new ArgumentException("The exact active object generation is required.", nameof(id));
        CheckGrowth(!_changes.ContainsKey(id));
        _changes.Remove(id);
        _removed.Add(id);
    }

    /// <summary>Saves at the current position of a borrowed stream. Stream output may be partial on failure.</summary>
    public PdfOperationReport Save(Stream output, PdfWriteOptions? options = null, CancellationToken cancellationToken = default)
    {
        Editable();
        if (output == null)
            throw new ArgumentNullException(nameof(output));
        if (!output.CanWrite)
            throw new ArgumentException("A writable stream is required.", nameof(output));
        return Run("WriteRevision", options ?? PdfWriteOptions.Default, cancellationToken, c =>
        {
            using var lease = new BorrowedStream(output, false, c);
            WriteCore(lease, options ?? PdfWriteOptions.Default, c);
        });
    }

    /// <summary>Stages a complete file in the destination directory and commits it atomically after every check succeeds.</summary>
    public PdfOperationReport SaveFile(string path, PdfWriteOptions? options = null, CancellationToken cancellationToken = default)
    {
        Editable();
        Guard.Text(path, nameof(path), 32767);
        var selected = options ?? PdfWriteOptions.Default;
        return Run("WriteRevisionFile", selected, cancellationToken, c => PdfAtomicFile.Write(path, c, s =>
        {
            using var lease = new BorrowedStream(s, false, c);
            WriteCore(lease, selected, c);
        }));
    }

    /// <summary>Discards this overlay; source graphs, streams and detached values remain valid.</summary>
    public void Dispose()
    {
        if (_disposed)
            return;
        if (_writing)
            throw new InvalidOperationException("Cannot dispose a transaction during saving.");
        _changes.Clear();
        _removed.Clear();
        _disposed = true;
    }

    internal void WriteCore(Stream output, PdfWriteOptions options, PdfOperationContext context, PdfObjectCrypt? crypt = null, bool validatedArchivalDowngrade = false, bool validatedSignatureEdit = false) => PdfWriterCore.Write(Source, _trailer, _changes, _removed, _maximum, _trailerChanged, output, options, context, crypt, validatedArchivalDowngrade, validatedSignatureEdit);
    private PdfOperationReport Run(string operation, PdfWriteOptions options, CancellationToken token, Action<PdfOperationContext> action)
    {
        Editable();
        token.ThrowIfCancellationRequested();
        var context = new PdfOperationContext(operation, "managed.writer", PdfCapability.WriteDocument, _policy, token);
        _writing = true;
        bool success = false;
        try
        {
            context.Checkpoint();
            action(context);
            context.EnsureComplete();
            success = true;
        }
        catch (Exception failure)
        {
            try
            {
                context.Checkpoint();
            }
            catch (Exception policyFailure)
            {
                if (!ReferenceEquals(failure, policyFailure))
                    policyFailure.Data["Fluent.Pdf.UnderlyingFailure"] = failure;
                throw;
            }

            throw;
        }
        finally
        {
            try
            {
                LastOperationReport = context.Finish(success);
            }
            finally
            {
                context.DisposeSources();
                _writing = false;
            }
        }

        return LastOperationReport!;
    }

    internal IEnumerable<PdfObjectId> ActiveIds(PdfOperationContext context)
    {
        var seen = new HashSet<int>();
        foreach (var id in _changes.Keys)
        {
            context.Checkpoint();
            context.Consume(PdfResourceKind.ExpandedBytes, 48);
            seen.Add(id.Number);
            if (!_removed.Contains(id))
                yield return id;
        }

        if (Source != null)
            foreach (var revision in Source.Revisions)
                foreach (var entry in revision.Entries)
                {
                    context.Checkpoint();
                    context.Consume(PdfResourceKind.Objects, 1);
                    if (seen.Contains(entry.Id.Number))
                        continue;
                    context.Consume(PdfResourceKind.ExpandedBytes, 48);
                    seen.Add(entry.Id.Number);
                    if (entry.Kind != PdfCrossReferenceKind.Free && !_removed.Contains(entry.Id))
                        yield return entry.Id;
                }
    }

    private bool Exists(PdfObjectId id)
    {
        if (id.Number == 0 || _removed.Contains(id))
            return false;
        if (_changes.ContainsKey(id))
            return true;
        if (Source != null)
            foreach (var revision in Source.Revisions)
                if (revision.Index.TryGetValue(id.Number, out var entry))
                    return entry.Kind != PdfCrossReferenceKind.Free && entry.Id == id;
        return false;
    }

    private void Alive()
    {
        if (_disposed)
            throw new ObjectDisposedException(nameof(PdfTransaction));
    }

    private void CheckGrowth(bool grows)
    {
        long entries = (long)_changes.Count + _removed.Count + (grows ? 1 : 0);
        if (entries > _policy.Limits.MaximumObjects)
            throw Failure("Limit.Objects", "The transaction object limit was reached.");
        if (entries > _policy.Limits.MaximumExpandedBytes / 128)
            throw Failure("Limit.ExpandedBytes", "The transaction overlay exceeds its configured state budget.");
    }

    private void Editable()
    {
        Alive();
        if (_writing)
            throw new InvalidOperationException("The transaction cannot be mutated or saved recursively during saving.");
    }

    private static PdfException Failure(string code, string message) => new(new PdfDiagnostic(code, message, PdfCapability.WriteDocument, "managed.writer"));
}
